// npm run init — turn a fresh clone of this template into a named system.
// Asks for the system abbreviation, the full Thai name, the basePath and the port, then rewrites
// every "⚠️ rename" spot plus the basePath/port settings. Safe to run again: it reads the current
// values back from the files, so answering with the same values changes nothing.
// .env.local (with a fresh NEXTAUTH_SECRET) is created only when it does not exist yet.
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createInterface } from 'node:readline'

const read = file => (existsSync(file) ? readFileSync(file, 'utf8') : null)

// Current values — the defaults offered at each prompt.
const theme = read('src/configs/themeConfig.ts')

if (!theme) {
  console.error('Run this from the project root (src/configs/themeConfig.ts not found).')
  process.exit(1)
}

const nextConfig = read('next.config.ts')
const pkg = read('package.json')

const current = {
  name: theme.match(/const templateName = '([^']*)'/)[1],
  subtitle: theme.match(/templateSubtitle: '([^']*)'/)[1],
  basePath: nextConfig.match(/^\s*basePath: '([^']*)'/m)?.[1] ?? '',
  port: pkg.match(/next dev[^"]*-p (\d+)/)?.[1] ?? '3000'
}

// Read answers through the line iterator (not rl.question) so piped input works too.
const rl = createInterface({ input: process.stdin })
const lines = rl[Symbol.asyncIterator]()

const ask = async (question, fallback) => {
  process.stdout.write(`${question} [${fallback}]: `)
  const { value = '' } = await lines.next()

  return value.trim() || fallback
}

const abbr = (await ask('System abbreviation, e.g. CAR', current.name.replace(/^MSU-/, ''))).toUpperCase()
const subtitle = await ask('Full Thai system name, e.g. ระบบขอใช้รถ มมส', current.subtitle)
let basePath = await ask('basePath, e.g. /car (empty = none: type -)', current.basePath || '-')
const port = await ask('Port', current.port)

rl.close()

basePath = basePath === '-' ? '' : `/${basePath.replace(/^\/+|\/+$/g, '')}`
const name = `MSU-${abbr.replace(/^MSU-/, '')}`

if (!/^MSU-[A-Z0-9-]+$/.test(name)) throw new Error(`Invalid abbreviation: ${abbr}`)
if (basePath && !/^\/[a-z0-9-_/]+$/i.test(basePath)) throw new Error(`Invalid basePath: ${basePath}`)
if (!/^\d{2,5}$/.test(port)) throw new Error(`Invalid port: ${port}`)
if (/['$`\\]/.test(subtitle)) throw new Error('The Thai name must not contain \' $ ` or \\')

// [file, [pattern, replacement]...] — patterns match whatever value is there now.
const edits = [
  [
    'src/configs/themeConfig.ts',
    [/const templateName = '[^']*'/, `const templateName = '${name}'`],
    [/templateSubtitle: '[^']*'/, `templateSubtitle: '${subtitle}'`]
  ],
  [
    'html/index.html',
    [/name: '[^']*',(\s*)\/\/ ⚠️ rename/, `name: '${name}',$1// ⚠️ rename`],
    [/subtitle: '[^']*'(\s*)\/\/ ⚠️ rename/, `subtitle: '${subtitle}'$1// ⚠️ rename`],
    [/<title>[^<]*<\/title>/, `<title>${name}</title>`]
  ],
  ['next.config.ts', [/^(\s*)basePath: '[^']*'/m, `$1basePath: '${basePath}'`]],
  ['package.json', [/"next dev --turbopack[^"]*"/, `"next dev --turbopack -p ${port}"`], [/"next start[^"]*"/, `"next start -p ${port}"`]],
  ['.claude/launch.json', [/"port": \d+/, `"port": ${port}`]],
  ['Dockerfile', [/EXPOSE \d+/, `EXPOSE ${port}`]],
  ['docker-compose.yml', [/"\d+:\d+"/, `"${port}:${port}"`]],
  ['deploy.ps1', [/--port \d+/, `--port ${port}`], [/Frontend: http:\/\/localhost:\d+/, `Frontend: http://localhost:${port}`]]
]

for (const [file, ...rules] of edits) {
  const before = read(file)

  if (before === null) continue
  const after = rules.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), before)

  if (after !== before) {
    writeFileSync(file, after)
    console.log(`updated ${file}`)
  }
}

// Secrets live only in .env.local — never overwrite an existing one.
if (existsSync('.env.local')) {
  console.log('.env.local exists — left untouched (check BASEPATH / NEXTAUTH_URL / port in it yourself)')
} else {
  const origin = `http://localhost:${port}`

  const env = (read('.env.example') ?? '')
    .replace(/^BASEPATH=.*\n/m, '')
    .replace(/^NEXT_PUBLIC_BASEPATH=.*$/m, () => `BASEPATH=${basePath}\nNEXT_PUBLIC_BASEPATH=\${BASEPATH}`)

  writeFileSync(
    '.env.local',
    `${env}\n# Generated by npm run init\nNEXTAUTH_URL=${origin}\${BASEPATH}/api/auth\nNEXTAUTH_SECRET=${randomBytes(32).toString('base64')}\n`,
    { mode: 0o600 }
  )
  console.log('created .env.local with a new NEXTAUTH_SECRET (fill in the ERP/API values)')
}

console.log(`\n${name} — ${subtitle} — http://localhost:${port}${basePath}/`)
